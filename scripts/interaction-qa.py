import json
import os
from pathlib import Path

switch_tab(os.environ['QA_TARGET'])
origin = os.environ.get('QA_ORIGIN', 'http://127.0.0.1:3015')
checks = []

def check(name, condition):
    assert condition, name
    checks.append(name)
    print('PASS:', name, flush=True)

cdp('Emulation.setDeviceMetricsOverride', width=390, height=844, deviceScaleFactor=1, mobile=False)
goto_url(origin)
wait(1)
js("document.querySelector('.mobile-toggle').click()")
wait(.4)
check('mobile menu opens', js("!!document.querySelector('[role=dialog]')"))
check('focus enters menu', js("document.querySelector('[role=dialog]').contains(document.activeElement)"))
for _ in range(12):
    press_key('Tab')
check('menu traps keyboard focus', js("document.querySelector('[role=dialog]').contains(document.activeElement)"))
press_key('Escape')
wait(.3)
check('Escape closes menu and restores focus', js("!document.querySelector('[role=dialog]') && document.activeElement.matches('.mobile-toggle')"))
js("document.querySelector('.mobile-toggle').click()")
wait(.3)
js("document.querySelector('[role=dialog] a[href=\"/our-expertise\"]').click()")
wait(1)
check('menu navigation closes drawer', js("location.pathname === '/our-expertise' && !document.querySelector('[role=dialog]')"))
goto_url(origin)
wait(1)
js("document.querySelector('.hero .next').click()")
check('hero next selects second slide and pauses', js("document.querySelector('.hero .carousel-track').style.transform.includes('-100%') && document.querySelector('.hero .carousel-pause').getAttribute('aria-pressed')==='true'"))
js("document.querySelector('.hero .previous').click()")
check('hero previous returns first slide', js("document.querySelector('.hero .carousel-track').style.transform.includes('0%')"))
js("document.querySelectorAll('.hero .carousel-dots button')[1].click()")
check('hero dots select slide', js("document.querySelectorAll('.hero .carousel-dots button')[1].getAttribute('aria-pressed')==='true'"))
js("document.querySelector('.project-carousel .next').click()")
check('project carousel advances', js("document.querySelector('.project-carousel .carousel-track').style.transform.includes('-100%')"))
goto_url(origin)
wait(1)
cdp('Input.dispatchMouseEvent', type='mouseMoved', x=0, y=0)
before = js("document.querySelector('.hero .carousel-track').style.transform")
wait(5.5)
check('hero autoplay advances', js("document.querySelector('.hero .carousel-track').style.transform") != before)
js("document.querySelector('.brand-card').focus()")
wait(.7)
check('brand keyboard focus slides front upward', js("parseFloat(getComputedStyle(document.querySelector('.brand-front')).transform.split(',')[5]) < -200"))
cdp('Emulation.setEmulatedMedia', features=[{'name':'prefers-reduced-motion','value':'reduce'}])
goto_url(origin)
wait(1)
before = js("document.querySelector('.hero .carousel-track').style.transform")
wait(5.5)
check('reduced motion disables autoplay', js("document.querySelector('.hero .carousel-track').style.transform") == before)
cdp('Emulation.setEmulatedMedia', features=[])
goto_url(origin + '/contact')
wait(1)
js("document.querySelector('form').requestSubmit()")
check('empty form exposes five errors', js("document.querySelectorAll('.field-error').length === 5"))
check('invalid form focuses first field', js("document.activeElement.name === 'firstName'"))
check('form does not claim delivery', js("!document.querySelector('.form-status').textContent.trim()"))
goto_url(origin + '/awards-articles')
wait(1)
article = js("document.querySelector('a[href^=\"/articles/\"]').getAttribute('href')")
goto_url(origin + article)
wait(1)
check('article detail renders on mobile', js("document.querySelectorAll('h1').length===1 && document.documentElement.scrollWidth<=innerWidth && !!document.querySelector('.article-body')"))
cdp('Emulation.setDeviceMetricsOverride', width=1440, height=900, deviceScaleFactor=1, mobile=False)
wait(.3)
check('article detail renders on desktop', js("document.documentElement.scrollWidth<=innerWidth"))
Path('artifacts/browser-qa/interactions.json').write_text(json.dumps({'origin':origin,'checks':checks},indent=2))
